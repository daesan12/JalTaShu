/**
 * 예측 대수 표기 — 소수 한 자리로 고정한다.
 *
 * 예측값은 소수로 온다(2.4, 1.9 …). **반올림하지 않는다** — 1.7과 1.9를 똑같이 "2대"로 쓰면
 * 서로 다른 값이라는 사실이 사라지고, 색·높이만 달라 보이는 화면이 된다(#105).
 * 소수 자체가 "추정치"라는 신호이기도 하다.
 *
 * 자리수가 흔들리면(2 / 2.4 / 2.45) 글자 폭이 칸마다 달라져 그래프 막대가 들쭉날쭉해 보인다.
 * `tabular-nums`와 함께 써야 자리가 맞는다.
 *
 * 대여소 상세 그래프(2-1)와 경로 비교·상세(10·11)가 **같은 함수를 쓴다** — 같은 종류의 숫자가
 * 화면마다 다르게 표기되면 다른 값으로 읽힌다.
 */
export function formatBikes(bikeCnt: number): string {
  return bikeCnt.toFixed(1);
}
