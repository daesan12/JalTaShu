--     1 반납 안내 / 2 안전수칙 / 3 약관 개정 / 4 설문조사 / 5 임시 폐쇄
--   순서가 어긋나면 팝업을 눌렀을 때 엉뚱한 공지가 열린다. seq 컬럼과 ORDER BY 가 그 순서를 지킨다.
--
-- ⚠ **notices 가 비어 있는 상태를 전제**한다. 이미 공지가 있으면 번호가 6부터 시작해 번들 팝업의
--   참조가 어긋난다. 적용 전에 SELECT COUNT(*) FROM notices 로 0 인지 확인한다.
--
-- 관리자(`@admin_login_id`)
--   notices.admin_id 는 NOT NULL 외래키라 admins 에 있는 관리자여야 한다. 번호를 직접 박지 않고
--   로그인 아이디로 찾아 쓰는 이유는 로컬·staging·운영에서 admin_id 가 서로 다르기 때문이다.
--   기본값 'admin' 은 AdminInitializer 가 기동 때 만드는 계정이다(application.properties 의
--   admin.bootstrap.id). 배포 환경이 ADMIN_BOOTSTRAP_ID 환경변수로 다른 아이디를 쓰고 있으면
--   그 값으로 바꿔야 한다.
--
-- ⚠ 아이디가 틀리면 **에러 없이 0건**이 들어간다. Flyway 는 그래도 성공으로 기록하고 넘어가며,
--   나중에 이 파일을 고쳐도 다시 실행되지 않는다. 적용 직후 반드시 건수를 확인한다.
--     SELECT COUNT(*) FROM notices;   -- 17 이어야 한다
--
-- ⚠ 터미널에서 이 파일을 직접 실행할 때는 문자셋을 지정해야 한다. 지정하지 않으면 클라이언트가
--   latin1 로 잡혀 한글이 이중 인코딩으로 들어간다(제목 길이가 31 이 아니라 73 으로 나온다).
--     mysql -u<사용자> -p <DB> --default-character-set=utf8mb4 < V3__seed_notices.sql
--   Flyway 로 적용할 때는 UTF-8 로 읽으므로 이 문제가 없다.
--
-- 팝업(popups)은 여기서 넣지 않는다. photo_url 이 S3 키라서 이미지를 먼저 올려야 하고,
-- 관리자 화면의 등록 흐름으로 만드는 편이 그 흐름까지 함께 검증된다. 팝업이 하나도 없으면
-- 앱은 번들된 기본 5장을 보여 준다(resolveNoticePopups).

